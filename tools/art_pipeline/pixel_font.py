GLYPH_HEIGHT = 7


def glyph_width(char: str) -> int:
    if char not in GLYPHS:
        raise KeyError(f"no glyph for {char!r}")
    return len(GLYPHS[char][0])


def text_width(text: str, scale: int = 1) -> int:
    """Rendered width in pixels: glyphs plus 1-column spacing between them."""
    if not text:
        return 0
    return sum((glyph_width(ch) + 1) * scale for ch in text) - scale


def draw_text(
    image: Image.Image,
    text: str,
    x: int,
    y: int,
    scale: int,
    color: RGBA,
    shadow: RGBA | None = None,
) -> int:
    """Stamp `text` at (x, y); returns the x just past the last glyph.

    A shadow, when given, is offset (+1, +1) px and drawn first so the
    face color always sits on top.
    """
    passes = ([(1, shadow)] if shadow else []) + [(0, color)]
    for offset, fill in passes:
        cx = x
        for ch in text:
            rows = GLYPHS[ch] if ch in GLYPHS else None
            if rows is None:
                raise KeyError(f"no glyph for {ch!r}")
            for gy, row in enumerate(rows):
                for gx, bit in enumerate(row):
                    if bit != "1":
                        continue
                    for sy in range(scale):
                        for sx in range(scale):
                            image.putpixel(
                                (cx + gx * scale + sx + offset,
                                 y + gy * scale + sy + offset),
                                fill,
                            )
            cx += (glyph_width(ch) + 1) * scale
    return x + text_width(text, scale)
